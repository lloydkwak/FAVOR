"""Generate the kinematics-only xArm7 URDF used by XArm7Kinematics (pytorch_kinematics).

Joint origins are taken verbatim from the official xarm_ros2 description
(xarm_description/config/kinematics/default/xarm7_default_kinematics.yaml, pinned commit in
README); joint limits are the official technical-specification ranges. A fixed
xarm_gripper_base_link (rotated pi about z, as in the Menagerie MJCF the simulator uses) and
link_tcp (0.172 m, xarm_gripper.urdf.xacro) are appended. No meshes or inertias: FK/IK only.

  python scripts/make_urdf.py --xarm-ros2 /path/to/xarm_ros2
"""
import argparse
import math
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from favor_xarm.config import load_config, resolve

HEADER = """<?xml version="1.0"?>
<!-- Generated by sim_xarm/scripts/make_urdf.py. Kinematics only.
     Joint origins: xarm_ros2 xarm7_default_kinematics.yaml (BSD-3-Clause, UFACTORY; see assets/NOTICE).
     Limits: official xArm7 technical specification. -->
<robot name="xarm7_favor">
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xarm-ros2", required=True)
    ap.add_argument("--out", default=resolve("assets/xarm7_favor.urdf"))
    args = ap.parse_args()
    kin = yaml.safe_load(open(os.path.join(args.xarm_ros2, "xarm_description", "config", "kinematics", "default",
                                           "xarm7_default_kinematics.yaml")))["kinematics"]
    cfg = load_config()
    lim = cfg["robot"]["joint_limits_deg"]
    vmax = math.radians(cfg["robot"]["max_joint_speed_deg"])
    s = [HEADER, '  <link name="link_base"/>\n']
    parent = "link_base"
    for i in range(1, 8):
        k = kin[f"joint{i}"]
        lo, hi = (math.radians(v) for v in lim[i - 1])
        s.append(f'  <link name="link{i}"/>\n')
        s.append(f'  <joint name="joint{i}" type="revolute">\n'
                 f'    <parent link="{parent}"/>\n    <child link="link{i}"/>\n'
                 f'    <origin xyz="{k["x"]} {k["y"]} {k["z"]}" rpy="{k["roll"]} {k["pitch"]} {k["yaw"]}"/>\n'
                 f'    <axis xyz="0 0 1"/>\n'
                 f'    <limit lower="{lo:.6f}" upper="{hi:.6f}" effort="50" velocity="{vmax:.6f}"/>\n  </joint>\n')
        parent = f"link{i}"
    s.append('  <link name="xarm_gripper_base_link"/>\n'
             '  <joint name="gripper_fix" type="fixed">\n    <parent link="link7"/>\n'
             '    <child link="xarm_gripper_base_link"/>\n'
             '    <!-- pi about z as in the Menagerie MJCF; xarm_ros2 attaches with identity. TODO(real): check -->\n'
             f'    <origin xyz="0 0 0" rpy="0 0 {math.pi:.9f}"/>\n  </joint>\n')
    s.append('  <link name="link_tcp"/>\n'
             '  <joint name="joint_tcp" type="fixed">\n    <parent link="xarm_gripper_base_link"/>\n'
             '    <child link="link_tcp"/>\n    <origin xyz="0 0 0.172" rpy="0 0 0"/>\n  </joint>\n')
    s.append("</robot>\n")
    open(args.out, "w").write("".join(s))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
